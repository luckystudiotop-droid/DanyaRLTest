class Map:
    def __init__(self):
        # Создаём копию матрицы, чтобы можно было изменять её (съедать точки)
        self.grid = [row[:] for row in DEFAULT_MAP]
        self.rows = len(self.grid)
        self.cols = len(self.grid[0])
        self.dots_left = self.count_dots()

    def count_dots(self):
        """Считает общее количество точек и энергетиков на карте."""
        count = 0
        for row in self.grid:
            for cell in row:
                if cell in (DOT, POWER_PELLET):
                    count += 1
        return count

    def is_wall(self, grid_x, grid_y):
        """Проверяет, является ли ячейка стеной."""
        # Выход за пределы сетки считаем стеной (кроме туннелей)
        if grid_y < 0 or grid_y >= self.rows:
            return True
        if grid_x < 0 or grid_x >= self.cols:
            return False  # Разрешаем движение вне границы для туннелей

        return self.grid[grid_y][grid_x] == WALL

    def eat_dot(self, grid_x, grid_y):
        """
        Проверяет, есть ли точка в ячейке, и съедает её.
        Возвращает:
          - 0: Ничего не съедено
          - DOT: Съедена обычная точка
          - POWER_PELLET: Съеден энергетик
        """
        if 0 <= grid_x < self.cols and 0 <= grid_y < self.rows:
            tile = self.grid[grid_y][grid_x]
            if tile in (DOT, POWER_PELLET):
                self.grid[grid_y][grid_x] = EMPTY
                self.dots_left -= 1
                return tile
        return EMPTY

    def draw(self, screen):
        """Отрисовывает карту, стены, точки и энергетики."""
        for y in range(self.rows):
            for x in range(self.cols):
                tile = self.grid[y][x]
                # Координаты центра ячейки
                center_x = x * TILE_SIZE + TILE_SIZE // 2
                center_y = y * TILE_SIZE + TILE_SIZE // 2
                # Отрисовка стены
                if tile == WALL:
                    rect = pygame.Rect(x * TILE_SIZE, y * TILE_SIZE, TILE_SIZE, TILE_SIZE)
                    pygame.draw.rect(screen, BLUE, rect, border_radius=4)
                # Отрисовка обычной точки
                elif tile == DOT:
                    pygame.draw.circle(screen, DOT_COLOR, (center_x, center_y), 3)
                # Отрисовка энергетика (большой точки)
                elif tile == POWER_PELLET:
                    pygame.draw.circle(screen, WHITE, (center_x, center_y), 7)